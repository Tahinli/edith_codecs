/// A grey JPEG whose scan runs out after two bytes. The one-bit Huffman codes make every zero bit
/// read as a coefficient, so without the stop at the end of the data every block would be filled
/// with garbage coefficients. The decode must return a picture of the declared size.
#[test]
fn a_scan_that_runs_out_of_data_stops_and_returns() {
    let mut jpeg = vec![0xff, 0xd8];
    // DQT: table 0, all ones.
    jpeg.extend_from_slice(&[0xff, 0xdb, 0x00, 67, 0x00]);
    jpeg.extend_from_slice(&[1; 64]);
    // SOF0: 8-bit, 4353x20297, one component (id 1, 1x1, quant 0).
    jpeg.extend_from_slice(&[0xff, 0xc0, 0x00, 11, 8, 0x4f, 0x49, 0x11, 0x01, 1, 1, 0x11, 0]);
    // DHT: DC table 0 and AC table 0, each one one-bit code ("0") -- size 0 for DC, the
    // coefficient "run 0, size 1" for AC.
    for (class_id, symbol) in [(0x00u8, 0u8), (0x10, 0x01)] {
        jpeg.extend_from_slice(&[0xff, 0xc4, 0x00, 20, class_id, 1]);
        jpeg.extend_from_slice(&[0; 15]);
        jpeg.push(symbol);
    }
    // SOS: one component, table 0/0, full spectral range, no successive approximation.
    jpeg.extend_from_slice(&[0xff, 0xda, 0x00, 8, 1, 1, 0x00, 0, 63, 0]);
    // The scan: two zero bytes, then the end of the image.
    jpeg.extend_from_slice(&[0x00, 0x00, 0xff, 0xd9]);
    let image = ec_image::decode(&jpeg).expect("a truncated scan decodes what it has");
    assert_eq!((image.width, image.height), (4353, 20297));
}
