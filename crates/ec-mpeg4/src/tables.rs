//! Tables of the MPEG-4 Part 2 decoder.
//!
//! The H.263 tables (MCBPC, CBPY, MVD, TCOEF, Advanced INTRA Coding, Modified
//! Quantization, scans, picture formats ...) live in `h263data.rs`, generated from the
//! text of ITU-T Rec. H.263, and are re-exported here. The tables below are specific to
//! ISO/IEC 14496-2 (MPEG-4 Part 2), which is not freely available. They were taken
//! from the constant tables of FFmpeg libavcodec n8.1 (LGPL) and could not yet be
//! re-sourced from a freely downloadable document:
//!
//! * `MPEG4_DCTAB_LUM`/`MPEG4_DCTAB_CHROM`: DC size VLCs.
//! * `MPEG4_INTRA_VLC`/`_RUN`/`_LEVEL`: INTRA TCOEF. Its codewords are
//!   those of Table 16/H.263 but the RUN/LEVEL assignment is MPEG-4's own.
//! * `INTER_RVLC`, `INTRA_RVLC` with `_RUN`/`_LEVEL`: reversible VLCs.
//! * `SPRITE_TRAJECTORY_LENS`: warping point displacement code lengths (dmv_length).
//! * `MB_TYPE_B_TAB`: B-VOP macroblock type codes.
//! * `MPEG4_DEFAULT_INTRA_MATRIX`/`MPEG4_DEFAULT_NON_INTRA_MATRIX`: default
//!   quantisation matrices.
//! * `MPEG4_Y_DC_SCALE_TABLE`/`MPEG4_C_DC_SCALE_TABLE`: DC scaler.
//! * `MPEG4_DC_THRESHOLD`: intra_dc_vlc_thr.
//! * `MPEG4_RL_INTRA_*`, `RVLC_RL_*`: entry counts of the tables above.

